-- -------------------------------------------------------------- INVOICES
CREATE TABLE IF NOT EXISTS invoices (
  id                    TEXT PRIMARY KEY,
  store_id              TEXT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  kind                  TEXT NOT NULL CHECK(kind IN ('purchase','sale')),
  invoice_number        TEXT NOT NULL,
  party_id              TEXT,
  invoice_date          TEXT NOT NULL,
  payment_method        TEXT NOT NULL DEFAULT 'cash' CHECK(payment_method IN ('cash','bank','bkash','nagad','other')),
  transaction_id        TEXT,
  notes                 TEXT,
  subtotal              REAL NOT NULL DEFAULT 0,
  tax_percent           REAL NOT NULL DEFAULT 0,
  discount              REAL NOT NULL DEFAULT 0,
  tax_amount            REAL NOT NULL DEFAULT 0,
  paid_amount           REAL NOT NULL DEFAULT 0,
  total_due             REAL NOT NULL DEFAULT 0,
  created_by            TEXT,
  verification_token    TEXT,
  custom_party_name     TEXT,
  custom_party_address  TEXT,
  custom_party_phone    TEXT,
  created_at            TEXT NOT NULL,
  updated_at            TEXT NOT NULL,
  UNIQUE(store_id, invoice_number)
);
CREATE INDEX IF NOT EXISTS idx_invoices_store_kind_date ON invoices(store_id, kind, invoice_date DESC);
CREATE UNIQUE INDEX IF NOT EXISTS invoices_verification_token_uq ON invoices(verification_token);

CREATE TABLE IF NOT EXISTS invoice_lines (
  id           TEXT PRIMARY KEY,
  invoice_id   TEXT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  item_id      TEXT NOT NULL REFERENCES inventory_items(id) ON DELETE RESTRICT,
  quantity     REAL NOT NULL,
  unit_price   REAL NOT NULL,
  line_total   REAL NOT NULL
);

CREATE TABLE IF NOT EXISTS expenses (
  id            TEXT PRIMARY KEY,
  store_id      TEXT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  expense_code  TEXT NOT NULL UNIQUE,
  expense_date  TEXT NOT NULL,
  details       TEXT NOT NULL,
  total         REAL NOT NULL,
  paid          REAL NOT NULL DEFAULT 0,
  due           REAL GENERATED ALWAYS AS (total - paid) STORED,
  note          TEXT,
  created_by    TEXT,
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS attendance (
  id               TEXT PRIMARY KEY,
  store_id         TEXT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  staff_id         TEXT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  attendance_date  TEXT NOT NULL,
  status           TEXT NOT NULL CHECK(status IN ('present','absent')),
  note             TEXT,
  recorded_by      TEXT,
  created_at       TEXT NOT NULL,
  UNIQUE(staff_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS device_logins (
  id                 TEXT PRIMARY KEY,
  store_id           TEXT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  staff_id           TEXT REFERENCES staff(id) ON DELETE SET NULL,
  device_fingerprint TEXT NOT NULL,
