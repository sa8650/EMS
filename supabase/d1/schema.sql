-- ============================================================================
-- EMS V1 · COMPLETE SCHEMA for Cloudflare D1 (SQLite)
-- ----------------------------------------------------------------------------
-- This is the SQLite counterpart of supabase/ems_complete_schema.sql.
-- Create a D1 database and apply this file with wrangler:
--
--   npx wrangler d1 create ems-d1
--   npx wrangler d1 execute ems-d1 --file=supabase/d1/schema.sql            # local
--   npx wrangler d1 execute ems-d1 --remote --file=supabase/d1/schema.sql  # prod
--
-- Conventions (mirrored by functions/_lib/db.js):
--   · uuid primary keys are TEXT (the driver generates crypto.randomUUID())
--   · bigint identity logs use INTEGER PRIMARY KEY AUTOINCREMENT
--   · booleans are INTEGER (0/1), jsonb / text[] are stored as TEXT (JSON)
--   · dates/timestamps are ISO-8601 TEXT
--   · _sequences backs invoice-number generation (RPC emulation in driver)
--   · business human codes (SUP-/CUS-/EXP-/ITM-) are generated by the driver
-- ============================================================================

-- ----------------------------------------------------------- CORE IDENTITIES
CREATE TABLE IF NOT EXISTS administrators (
  id            TEXT PRIMARY KEY,
  name          TEXT NOT NULL,
  address       TEXT,
  phone         TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  admin_code    TEXT NOT NULL UNIQUE,
  active        INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS ems_owners (
  id            TEXT PRIMARY KEY,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  active        INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS stores (
  id                   TEXT PRIMARY KEY,
  admin_id             TEXT NOT NULL REFERENCES administrators(id) ON DELETE RESTRICT,
  name                 TEXT NOT NULL,
  address              TEXT,
  phone                TEXT NOT NULL,
  phone2               TEXT,
  email                TEXT,
  website              TEXT,
  shop_code            TEXT NOT NULL UNIQUE,
  category             TEXT NOT NULL DEFAULT 'General Store',
  status               TEXT NOT NULL DEFAULT 'inactive' CHECK(status IN ('active','inactive','read_only')),
  low_stock_threshold  REAL NOT NULL DEFAULT 5,
  created_at           TEXT NOT NULL,
  updated_at           TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_stores_admin ON stores(admin_id);

-- --------------------------------------------------------------- LICENSING
CREATE TABLE IF NOT EXISTS license_plans (
  id                          TEXT PRIMARY KEY,
  title                       TEXT NOT NULL,
  duration_months             INTEGER NOT NULL,
  max_stores                  INTEGER NOT NULL,
  benefits                    TEXT NOT NULL DEFAULT '',
  payment_details             TEXT NOT NULL DEFAULT '',
  price                       REAL NOT NULL DEFAULT 0,
  active                      INTEGER NOT NULL DEFAULT 1,
  connectx_enabled            INTEGER NOT NULL DEFAULT 0,
  connectx_daily_limit        INTEGER NOT NULL DEFAULT 0,
  zudo_enabled                INTEGER NOT NULL DEFAULT 0,
  zudo_daily_limit            INTEGER NOT NULL DEFAULT 0,
  business_health_enabled     INTEGER NOT NULL DEFAULT 0,
  business_health_daily_limit INTEGER NOT NULL DEFAULT 0,
  truebill_enabled            INTEGER NOT NULL DEFAULT 0,
  vaultium_gb                 INTEGER NOT NULL DEFAULT 0,
  created_at                  TEXT NOT NULL,
  updated_at                  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS licenses (
  id                          TEXT PRIMARY KEY,
  admin_id                    TEXT NOT NULL REFERENCES administrators(id) ON DELETE CASCADE,
  store_id                    TEXT REFERENCES stores(id) ON DELETE CASCADE,
  plan_id                     TEXT REFERENCES license_plans(id) ON DELETE SET NULL,
  duration_months             INTEGER NOT NULL,
  amount                      REAL NOT NULL DEFAULT 0,
  max_stores                  INTEGER NOT NULL DEFAULT 1,
  payment_method              TEXT NOT NULL CHECK(payment_method IN ('bkash','nagad','other')),
  payment_number              TEXT NOT NULL,
  transaction_id              TEXT NOT NULL,
  status                      TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','active','expired','rejected')),
  connectx_enabled            INTEGER NOT NULL DEFAULT 0,
  connectx_daily_limit        INTEGER NOT NULL DEFAULT 0,
  zudo_enabled                INTEGER NOT NULL DEFAULT 0,
  zudo_daily_limit            INTEGER NOT NULL DEFAULT 0,
  business_health_enabled     INTEGER NOT NULL DEFAULT 0,
  business_health_daily_limit INTEGER NOT NULL DEFAULT 0,
  truebill_enabled            INTEGER NOT NULL DEFAULT 0,
  vaultium_gb                 INTEGER NOT NULL DEFAULT 0,
  transaction_type            TEXT NOT NULL DEFAULT 'new' CHECK(transaction_type IN ('new','renewal','upgrade','downgrade')),
  starts_at                   TEXT,
  expires_at                  TEXT,
  reviewed_at                 TEXT,
  reviewed_by                 TEXT,
  review_note                 TEXT,
  created_at                  TEXT NOT NULL,
  UNIQUE(payment_method, transaction_id)
);
CREATE INDEX IF NOT EXISTS idx_licenses_status ON licenses(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_licenses_admin_status ON licenses(admin_id, status);
CREATE INDEX IF NOT EXISTS idx_licenses_admin_entitlements ON licenses(admin_id, status, connectx_enabled, starts_at, expires_at);

CREATE TABLE IF NOT EXISTS current_entitlements (
  admin_id                    TEXT PRIMARY KEY REFERENCES administrators(id) ON DELETE CASCADE,
  current_license_id          TEXT REFERENCES licenses(id) ON DELETE SET NULL,
  shop_limit                  INTEGER NOT NULL DEFAULT 0,
